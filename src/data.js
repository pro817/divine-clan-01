function makeBaseCharacters(){
  const chars = {};
  const pKeys = ['P1','P2','P3','P4','P5','P6'];
  const mKeys = ['M1','M2','M3','M4','M5','M6'];
  let idx = 0;
  for (const p of pKeys){
    for (let mi=0; mi<mKeys.length; mi++){
      const m = mKeys[mi];
      const id = `${p}_${m}`;
      const name = pNames[p][mi];
      const play = playStyles[p];
      const pers = personalityStyles[m];
      const pt = playText[p];
      const mt = moodText[m];
      chars[id] = {
        id,
        characterName: name,
        maleName: maleNames[idx],
        femaleName: femaleNames[idx],
        playStyle: play.label,
        personalityStyle: pers.label,
        summary: `${play.label} 움직임에 ${pers.label} 성향이 섞인 타입이야.`,
        tags: [play.label, pers.label, idx % 2 === 0 ? '균형형' : '실전형'],
        interpretation: {
          appearance: appearancePool[idx % appearancePool.length],
          playStyleText: pt.body,
          personalityText: mt.body,
          teamView: `${pt.body.split('.')[0]}. ${mt.team}`,
          strengths: `${pt.strength} ${mt.addStrength}`,
          weaknesses: `${pt.weakness} ${mt.addWeakness}`
        },
        impressiveScene: pt.scene,
        successQuote: pt.quote,
        deathScene: pt.death,
        lastQuote: pt.last
      };
      idx++;
    }
  }
  return chars;
}

